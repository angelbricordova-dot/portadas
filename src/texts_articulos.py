def n_sentences(article):
    return sum(len(s) for _, s in article)


def take(article, n):
    """Primeros n oraciones del artículo, agrupadas en sus párrafos: [(antetítulo, texto), ...]."""
    out = []
    left = n
    for head, sents in article:
        if left <= 0:
            break
        part = sents[:left]
        left -= len(part)
        out.append((head if part else None, " ".join(part)))
    return out
